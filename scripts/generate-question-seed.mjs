import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const outPath = path.join(root, 'supabase', 'migrations', '0037_seed_questions.sql');
const tmpDir = path.join(root, '.tmp', 'question-seed-topic');

function sql(value) {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function jsonb(value) {
  if (value === undefined) return 'null';
  return `${sql(JSON.stringify(value))}::jsonb`;
}

function listJsonFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listJsonFiles(full));
    else if (entry.isFile() && entry.name.endsWith('.json')) out.push(full);
  }
  return out;
}

async function loadTopicHelpers() {
  fs.rmSync(tmpDir, { recursive: true, force: true });
  fs.mkdirSync(tmpDir, { recursive: true });
  try {
    execFileSync(
      path.join(root, 'node_modules', '.bin', process.platform === 'win32' ? 'tsc.cmd' : 'tsc'),
      [
        'src/data/topicAlias.ts',
        'src/data/subjects.ts',
        'src/types/question.ts',
        '--module',
        'ES2020',
        '--target',
        'ES2020',
        '--moduleResolution',
        'node',
        '--skipLibCheck',
        '--outDir',
        tmpDir,
        '--noEmitOnError',
        'false',
      ],
      { cwd: root, stdio: 'pipe' },
    );
  } catch {
    // tsc can report unresolved path-alias type imports while still emitting
    // usable runtime JS. The emitted files are what we need here.
  }

  const aliasPath = path.join(tmpDir, 'data', 'topicAlias.js');
  if (fs.existsSync(aliasPath)) {
    const patched = fs
      .readFileSync(aliasPath, 'utf8')
      .replace("from './subjects';", "from './subjects.js';");
    fs.writeFileSync(aliasPath, patched);
    return import(pathToFileURL(aliasPath).href);
  }
  return { canonicalTopic: () => null };
}

function normalizeBank(raw, sourcePath) {
  if (Array.isArray(raw)) {
    return raw.filter(Boolean);
  }
  if (raw && Array.isArray(raw.questions)) {
    return raw.questions.filter(Boolean);
  }
  throw new Error(`Unsupported question bank shape: ${sourcePath}`);
}

function isPlayable(q) {
  if (!q || q.type !== 'multiple_choice') return false;
  if (q.status === 'restored' || q.status === 'deprecated') return false;
  if (q.needsDistractors) return false;
  if (!Array.isArray(q.choices) || q.choices.length === 0) return false;
  if (!Number.isInteger(q.answerIndex)) return false;
  if (q.answerIndex < 0 || q.answerIndex >= q.choices.length) return false;
  return true;
}

const { canonicalTopic } = await loadTopicHelpers();
const questionDir = path.join(root, 'src', 'data', 'questions');
const files = listJsonFiles(questionDir).sort();
const rows = [];
const seen = new Set();

for (const file of files) {
  const rel = path.relative(root, file).replaceAll(path.sep, '/');
  const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const q of normalizeBank(raw, rel)) {
    if (!isPlayable(q)) continue;
    if (seen.has(q.id)) {
      throw new Error(`Duplicate question id: ${q.id}`);
    }
    seen.add(q.id);
    const canonical = canonicalTopic(q.subject, q.chapter, q.topic) ?? q.topic;
    rows.push({
      id: q.id,
      subject: q.subject,
      chapter: q.chapter,
      chapterTitle: q.chapterTitle ?? '',
      topic: q.topic ?? '',
      canonicalTopic: canonical,
      subtopic: q.subtopic ?? null,
      passNumber: q.pass ?? 1,
      difficulty: q.difficulty ?? null,
      stem: q.question,
      choices: q.choices,
      answerIndex: q.answerIndex,
      explanation: q.explanation ?? null,
      lifecycle: q.status ?? 'curated',
      isPlayable: true,
      sourcePath: rel,
    });
  }
}

const chunks = [];
for (let i = 0; i < rows.length; i += 80) chunks.push(rows.slice(i, i + 80));

let body = `-- Generated by scripts/generate-question-seed.mjs. Do not edit by hand.\n`;
body += `-- Playable question count: ${rows.length}\n\n`;

for (const chunk of chunks) {
  body += `insert into public.questions (\n`;
  body += `  id, subject, chapter, chapter_title, topic, canonical_topic, subtopic,\n`;
  body += `  pass_number, difficulty, stem, choices, answer_index, explanation,\n`;
  body += `  lifecycle, is_playable, source_path, updated_at\n`;
  body += `) values\n`;
  body += chunk
    .map((r) =>
      [
        sql(r.id),
        sql(r.subject),
        r.chapter,
        sql(r.chapterTitle),
        sql(r.topic),
        sql(r.canonicalTopic),
        sql(r.subtopic),
        r.passNumber,
        r.difficulty === null ? 'null' : r.difficulty,
        sql(r.stem),
        jsonb(r.choices),
        r.answerIndex,
        jsonb(r.explanation),
        sql(r.lifecycle),
        r.isPlayable ? 'true' : 'false',
        sql(r.sourcePath),
        'now()',
      ].join(', '),
    )
    .map((line) => `  (${line})`)
    .join(',\n');
  body += `\non conflict (id) do update set\n`;
  body += `  subject = excluded.subject,\n`;
  body += `  chapter = excluded.chapter,\n`;
  body += `  chapter_title = excluded.chapter_title,\n`;
  body += `  topic = excluded.topic,\n`;
  body += `  canonical_topic = excluded.canonical_topic,\n`;
  body += `  subtopic = excluded.subtopic,\n`;
  body += `  pass_number = excluded.pass_number,\n`;
  body += `  difficulty = excluded.difficulty,\n`;
  body += `  stem = excluded.stem,\n`;
  body += `  choices = excluded.choices,\n`;
  body += `  answer_index = excluded.answer_index,\n`;
  body += `  explanation = excluded.explanation,\n`;
  body += `  lifecycle = excluded.lifecycle,\n`;
  body += `  is_playable = excluded.is_playable,\n`;
  body += `  source_path = excluded.source_path,\n`;
  body += `  updated_at = now();\n\n`;
}

fs.writeFileSync(outPath, body);
console.log(`Wrote ${rows.length} questions to ${path.relative(root, outPath)}`);
